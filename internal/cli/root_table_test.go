var probeGroups = map[string]string{"cache probeprov": "Test entries"}

// probeRoot is today's tree with probeLeaf mounted; got receives what the
// handler was given.
func probeRoot(t *testing.T, got *leafInput) *cobra.Command {
	t.Helper()
	root := newRoot(tcl)
	h := map[capability.Key]handler{probeLeaf.Key: func(cl *call, ctx context.Context, in leafInput) error {
		if cl != tcl {
			t.Error("the handler runs outside the command's call")
		}
		*got = in
		return nil
	}}
	if err := mountLeaves(root, []capability.Leaf{probeLeaf}, h, probeGroups); err != nil {
		t.Fatal(err)
	}
	return root
}

func TestBuildLeafFromTable(t *testing.T) {
	var in leafInput
	root := probeRoot(t, &in)
	c, rest, err := root.Find([]string{"cache", "probeprov", "probe"})
	if err != nil || len(rest) != 0 || c.Name() != "probe" {
		t.Fatalf("the leaf is not at its words: %v %v %v", c, rest, err)
	}
	if c.Short != probeLeaf.Short || c.Example != probeLeaf.Example || !slices.Equal(c.Aliases, []string{"pr"}) {
		t.Errorf("text: %q %q %v", c.Short, c.Example, c.Aliases)
	}
	if c.Use != "probe NAME [ITEM]" {
		t.Errorf("use: %q", c.Use)
	}
	if g := c.Parent(); g.Name() != "probeprov" || g.Short != "Test entries" || g.Parent().Name() != "cache" || g.Runnable() {
		t.Errorf("group: %q %q under %q, runnable %v", g.Name(), g.Short, g.Parent().Name(), g.Runnable())
	}
	if cache, _, _ := root.Find([]string{"cache"}); cache.Parent() != root || len(cache.Commands()) < 2 {
		t.Error("the leaf did not join today's cache command")
	}
	for _, x := range []*cobra.Command{c, c.Parent()} {
		if x.PersistentPreRunE != nil || x.PersistentPreRun != nil || x.PreRunE != nil {
			t.Errorf("%s sets its own hook: the root's begin would not run", x.CommandPath())
		}
	}
	want := map[string]string{"to": "", "fast": "false", "mode": "a", "n": "3", "wait": "1m", "max": "1KiB", "tag": "[]", "slow": "false", "level": ""}
	for name, def := range want {
		f := c.Flags().Lookup(name)
		if f == nil {
			t.Errorf("--%s missing", name)
			continue
		}
		if f.DefValue != def {
			t.Errorf("--%s default %q, want %q", name, f.DefValue, def)
		}
	}
	if c.Flags().Lookup("seed") != nil {
		t.Error("--seed is generated by komando: a person never types it")
	}
	if cmdID(c) != "cache.probeprov.probe" {
		t.Errorf("ID %q", cmdID(c))
	}
}

func TestBuildLeafRunsHandler(t *testing.T) {
	invHome(t)
	var in leafInput
	run := func(args ...string) error {
		in = leafInput{}
		root := probeRoot(t, &in) // flags keep their values between runs of one tree
		line := append([]string{"cache", "probeprov", "probe"}, args...)
		openPath(root, line)
		root.SetArgs(line)
		_, err := root.ExecuteC()
		return err
	}
	if err := run("c1", "--to", "f", "--fast", "--mode", "b", "--n", "7", "--wait", "2h", "--max", "2KiB", "--tag", "x", "--tag", "y", "--level", "9"); err != nil {
		t.Fatal(err)
	}
	if !slices.Equal(in.Args, []string{"c1"}) || in.String("to") != "f" || !in.Bool("fast") || in.String("mode") != "b" ||
		in.Int("n") != 7 || in.Duration("wait") != 2*time.Hour || in.Bytes("max") != 2048 ||
		!slices.Equal(in.Strings("tag"), []string{"x", "y"}) || in.String("level") != "9" || !in.Changed("mode") || in.Changed("slow") {
		t.Errorf("the handler got %+v", in)
	}
	for _, bad := range [][]string{
		{"c1"},                                        // --to is required
		{"c1", "--to", "f", "--mode", "c"},            // not one of a, b
		{"c1", "--to", "f", "--fast", "--slow"},       // conflicts
		{"c1", "--to", "f", "--level", "9"},           // needs --fast
		{"c1", "--to", "f", "--fast", "--level", "x"}, // the pattern
		{"--to", "f"},                                 // NAME is missing
		{"c1", "i", "extra", "--to", "f"},             // too many
	} {
		if e := toErr(run(bad...)); e == nil || e.Code != "USAGE" {
			t.Errorf("%v: want USAGE, got %v", bad, e)
		}
		if in.Args != nil {
			t.Errorf("%v: the handler ran", bad)
		}
	}
}

func TestBuildRefusesWhatItCannotBuild(t *testing.T) {
	h := func(*call, context.Context, leafInput) error { return nil }
	cases := map[string]struct {
		leaf   capability.Leaf
		groups map[string]string
		want   string
	}{
		"a path today's tree has": {capability.Leaf{Key: capability.Key{Type: "cache", Provider: "redis", Verb: "raw"}, Short: "x"}, nil, "already"},
		"no text":                 {capability.Leaf{Key: capability.Key{Type: "cache", Provider: "probeprov", Verb: "probe"}}, probeGroups, "Short"},
		"a group with no text":    {capability.Leaf{Key: capability.Key{Type: "cache", Provider: "other", Verb: "probe"}, Short: "x"}, probeGroups, "group"},
		"a global flag":           {capability.Leaf{Key: probeLeaf.Key, Short: "x", Options: []capability.Option{{Name: "dry-run", Kind: capability.Bool}}}, probeGroups, "global flag"},
		"an option named help":    {capability.Leaf{Key: probeLeaf.Key, Short: "x", Options: []capability.Option{{Name: "help", Kind: capability.Bool}}}, probeGroups, "global flag"},
	}
	for name, c := range cases {
		err := mountLeaves(newRoot(tcl), []capability.Leaf{c.leaf}, map[capability.Key]handler{c.leaf.Key: h}, c.groups)
		if err == nil || !strings.Contains(err.Error(), c.want) {
			t.Errorf("%s: %v, want an error naming %q", name, err, c.want)
		}
	}
	// names and aliases of one level never meet (R3): cobra would pick one
	// silently
	small := func() *cobra.Command {
		root := &cobra.Command{Use: "komando"}
		cache := &cobra.Command{Use: "cache"}
		cache.AddCommand(&cobra.Command{Use: "keep", Aliases: []string{"kp"}, Run: func(*cobra.Command, []string) {}})
		root.AddCommand(cache)
		return root
	}
	for name, l := range map[string]capability.Leaf{
		"a synonym that is a sibling's name":  {Key: capability.Key{Type: "cache", Verb: "hold"}, Short: "x", Synonyms: []string{"keep"}},
		"a synonym that is a sibling's alias": {Key: capability.Key{Type: "cache", Verb: "hold"}, Short: "x", Synonyms: []string{"kp"}},
		"a name that is a sibling's alias":    {Key: capability.Key{Type: "cache", Verb: "kp"}, Short: "x"},
	} {
		err := mountLeaves(small(), []capability.Leaf{l}, map[capability.Key]handler{l.Key: h}, nil)
		if err == nil || !strings.Contains(err.Error(), "already") {
			t.Errorf("%s: %v, want an error saying the word is already used", name, err)
		}
	}
	// a planned leaf and a leaf with no handler are not built
	planned := probeLeaf
	planned.State = capability.New
	root := newRoot(tcl)
	if err := mountLeaves(root, []capability.Leaf{planned}, map[capability.Key]handler{planned.Key: h}, probeGroups); err == nil {
		t.Error("a handler for a planned leaf was accepted")
	}
	if err := mountLeaves(root, []capability.Leaf{probeLeaf}, nil, probeGroups); err != nil {
		t.Fatal(err)
	}
	if c, _, _ := root.Find([]string{"cache", "probeprov"}); c.Name() == "probeprov" {
		t.Error("a leaf with no handler was built")
	}
}

// Every handler serves a built leaf of the table, and a leaf whose type
// has moved (step C, one type per pull request) has a handler. When every
// type has moved, today's constructors are gone.
func TestEveryHandlerHasLeaf(t *testing.T) {
	built := map[capability.Key]bool{}
	for _, l := range capability.All() {
		if l.State == capability.Built {
			built[l.Key] = true
		}
	}
	for k := range handlers {
		if !built[k] {
			t.Errorf("handler for %s: no built leaf has that key", k)
		}
		if !slices.Contains(movedTypes, k.Type) && !(k.Type == "" && slices.Contains(movedTop, k.Verb)) {
			t.Errorf("handler for %s: its type is not in movedTypes", k)
		}
	}
	for k := range built {
		if slices.Contains(movedTypes, k.Type) && handlers[k] == nil {
			t.Errorf("%s: its type has moved but it has no handler", k)
		}
	}
}

// walk calls f for every command under c, c too.
func walk(c *cobra.Command, f func(*cobra.Command)) {
	f(c)
	for _, s := range c.Commands() {
		walk(s, f)
	}
}

// The builder reads the table's defaults and patterns as written; each one
// must parse, so no option starts at a silent zero.
func TestBuiltDefaultsParse(t *testing.T) {
	for _, l := range capability.All() {
		for _, o := range l.Options {
			var err error
			switch {
			case o.Default == "":
			case o.Kind == capability.Int:
				_, err = strconv.Atoi(o.Default)
			case o.Kind == capability.Duration:
				_, err = parseSpan(o.Default)
			case o.Kind == capability.Bytes:
				_, err = parseSize(o.Default)
			case o.Kind == capability.Bool && o.Default != "true" && o.Default != "false":
				err = fmt.Errorf("not true or false")
			case o.Kind == capability.Enum && !slices.Contains(o.Enum, o.Default):
				err = fmt.Errorf("not one of %v", o.Enum)
			}
			if err != nil {
				t.Errorf("%s --%s default %q: %v", l.Key, o.Name, o.Default, err)
			}
			if o.Pattern != "" {
				if _, err := regexp.Compile(o.Pattern); err != nil {
					t.Errorf("%s --%s pattern: %v", l.Key, o.Name, err)
				}
			}
		}
	}
}

// withTable mounts leaves with hs through the real entry (newRoot) for one
// test: the package's table, handlers and group texts come back after it.
func withTable(t testing.TB, leaves []capability.Leaf, hs map[capability.Key]handler, groups map[string]string) {
	t.Helper()
	oldLeaves, oldHandlers, oldGroups := tableLeaves, handlers, groupShorts
	tableLeaves = func() []capability.Leaf { return append(oldLeaves(), leaves...) }
	handlers, groupShorts = maps.Clone(oldHandlers), maps.Clone(oldGroups)
	maps.Copy(handlers, hs)
	maps.Copy(groupShorts, groups)
	t.Cleanup(func() { tableLeaves, handlers, groupShorts = oldLeaves, oldHandlers, oldGroups })
}

// A command of today goes only when every built leaf that names its ID has
// a handler: conn kinds stays while one carrier waits. A command that exec,
// query or raw replaces stays for cut step D. (Audit R1, R3; cut-c 1, 2)
func TestHideWaitsForEveryCarrier(t *testing.T) {
	h := func(*call, context.Context, leafInput) error { return nil }
	a := capability.Leaf{Key: capability.Key{Type: "cache", Provider: "probeprov", Verb: "kinds"}, Short: "x", Carries: []string{"conn.kinds"}}
	b := capability.Leaf{Key: capability.Key{Type: "cache", Provider: "probeprov", Verb: "kinds2"}, Short: "x", Carries: []string{"conn.kinds"}}
	r := capability.Leaf{Key: capability.Key{Type: "cache", Provider: "probeprov", Verb: "rawish"}, Short: "x", Carries: []string{"db.info"}}
	has := func(id string) bool { return commandWithID(newRoot(tcl), id) != nil }
	withTable(t, []capability.Leaf{a, b, r}, map[capability.Key]handler{a.Key: h, r.Key: h}, probeGroups)
	if !has("conn.kinds") {
		t.Error("conn kinds went while one of its carriers has no handler")
	}
	if !has("db.info") {
		t.Error("db info went before cut step D: query replaces it")
	}
	withTable(t, nil, map[capability.Key]handler{b.Key: h}, nil)
	if has("conn.kinds") {
		t.Error("conn kinds stayed after every carrier moved")
	}
	if !has("cache.probeprov.kinds") || !has("cache.probeprov.kinds2") {
		t.Error("the carriers are not in the tree")
	}
}

// Every v0.17 ID is in the mounted tree, or every built leaf that names it
// has a handler: no command vanishes while a carrier waits, and none is
// there twice. The v0.17 list is frozen (capability/testdata), because the
// cut renames testdata/command_ids.txt. (Audit R1, R3)
func TestTodayIDsStayUntilCarried(t *testing.T) {
	b, err := os.ReadFile(filepath.Join("..", "capability", "testdata", "v0_17_ids.txt"))
	if err != nil {
		t.Fatal(err)
	}
	carried := map[string]bool{}
	for _, l := range tableLeaves() {
		for _, id := range slices.Concat(l.Today, l.Carries) {
			if l.State == capability.Built {
				carried[id] = carried[id] || handlers[l.Key] == nil
			}
		}
	}
	paths, ids := map[string]bool{}, map[string]int{}
	walk(newRoot(tcl), func(c *cobra.Command) {
		if paths[c.CommandPath()] {
			t.Errorf("%q is in the tree twice", c.CommandPath())
		}
		paths[c.CommandPath()] = true
		if c.Annotations[cmdIDNote] == "" || cmdID(c) == strings.ReplaceAll(strings.TrimPrefix(c.CommandPath(), "komando "), " ", ".") {
			ids[cmdID(c)]++ // a wrapper (withID) shares the ID of what it runs
		}
	})
	for id, n := range ids {
		if n > 1 {
			t.Errorf("ID %s is in the tree %d times", id, n)
		}
	}
	today := strings.Fields(string(b))
	left := func(id string) bool {
		if ids[id] > 0 || slices.Contains(removedIDs, id) { // step D took it out of the tree on purpose (root_removed.go)
			return false
		}
		waiting, named := carried[id]
		return !named || waiting
	}
	for _, id := range today {
		if !left(id) {
			continue
		}
		// a group's fate is its children's: it may leave once none of them waits
		under := func(c string) bool { return strings.HasPrefix(c, id+".") }
		if slices.Contains(capability.Groups(), id) && slices.ContainsFunc(today, under) &&
			!slices.ContainsFunc(today, func(c string) bool { return under(c) && left(c) }) {
			continue
		}
		t.Errorf("%s left the tree, but no leaf does it yet", id)
	}
}

// The root's hook runs once for a table leaf, before its handler: begin,
// the start checks and the personal-data switch; a dry-run stop shows as
// would_be_blocked. (Audit R5)
func TestTableLeafRunsThroughTheRoot(t *testing.T) {
	invHome(t)
	var dry, personal bool
	h := func(cl *call, _ context.Context, in leafInput) error {
		dry, personal = cl.gate().dryRun, cl.personalCmd
		if err := cl.policyStop(out.Errf(out.ExitPolicy, "NEEDS_PERSON", "a person runs it", "probe stop")); err != nil {
			return err
		}
		cl.out.Print("cache.probeprov.probe", map[string]any{"ran": true}, nil)
		return nil
	}
	withTable(t, []capability.Leaf{probeLeaf}, map[capability.Key]handler{probeLeaf.Key: h}, probeGroups)
	personalCmds["cache probeprov probe"] = true
	t.Cleanup(func() { delete(personalCmds, "cache probeprov probe") })

	root := newRoot(tcl)
	hook, runs := root.PersistentPreRunE, 0
	root.PersistentPreRunE = func(c *cobra.Command, a []string) error { runs++; return hook(c, a) }
	line := []string{"cache", "probeprov", "probe", "c1", "--to", "f", "--dry-run"}
	openPath(root, line)
	root.SetArgs(line)
	if _, err := root.ExecuteC(); err != nil {
		t.Fatal(err)
	}
	if runs != 1 || !dry {
		t.Errorf("the root's hook ran %d times (dry run seen: %v), want once", runs, dry)
	}
	setGate(tcl, false, gateDryRun)
	setCallerEnv(t, "KOMANDO_AGENT", "1")
	d, e := invRun(t, "--dry-run", "cache", "probeprov", "probe", "c1", "--to", "f")
	if e != nil || blockedCode(d) != "NEEDS_PERSON" {
		t.Errorf("a dry run reports the leaf's stop: %v %+v", d, e)
	}
	if !personal {
		t.Error("the personal-data switch did not reach the leaf")
	}
	setGate(tcl, false, gateDryRun)
}

// safetyAnswers is what every table keyed by command ID says about c: the
// masking switch, the local reads, the root's home rule, the kind, the
// risk row, and the ssh-gate's answers. A table keyed by safety key
// answers through cmdKeys.
func safetyAnswers(c *cobra.Command) map[string]string {
	id := cmdID(c)
	kind, _ := kindOf(c)
	a := idAnswers(id)
	a["kind"] = fmt.Sprint(kind)
	a["risk"] = riskOf(c, nil).tier.String()
	a["gateHere"] = gateHere(c, id)
	a["gateWrites"] = gateWrites(c, id)
	a["gateLocalRead"] = gateLocalRead(c, id)
	a["gateEgress"] = gateEgress(c, id)
	return a
}

// idAnswers are the answers of the tables keyed by command ID for id:
// cmdKeys and every table of idTables.
func idAnswers(id string) map[string]string {
	a := map[string]string{"cmdKeys": fmt.Sprint(cmdKeys[id])}
	for _, tb := range idTables() {
		a[tb.name] = entryText(tb.get(id))
	}
	return a
}

// entryText is an idTable entry as a test compares it: a gate func by
// whether it checks anything.
func entryText(v any, ok bool) string {
	switch {
	case !ok:
		return "none"
	case noCheck(v):
		return "entry, no check"
	case reflect.ValueOf(v).Kind() == reflect.Func:
		return "entry, a check"
	}
	return fmt.Sprint(v)
}

// tablesFollow says where the moved command's answers differ from those of
// today's command it does, one line per table.
func tablesFollow(today, moved *cobra.Command) []string {
	old, now := safetyAnswers(today), safetyAnswers(moved)
	var diff []string
	for _, k := range slices.Sorted(maps.Keys(old)) {
		if old[k] != now[k] {
			diff = append(diff, fmt.Sprintf("%s: %s says %q for %s, %q for %s", k, k, old[k], cmdID(today), now[k], cmdID(moved)))
		}
	}
	return diff
}

// Every table keyed by command ID gives a moved leaf the answer it gave
// today's command: masking stays on, a key's person-only list holds, the
// gate keeps reading the same files. One C pull request per type moves
// the noun's table entries in the same commit. (Audit R4)
func TestSafetyTablesFollowTheLeaf(t *testing.T) {
	oldHandlers := handlers
	handlers = map[capability.Key]handler{}
	today := newRoot(tcl)
	handlers = oldHandlers
	moved := newRoot(tcl)
	for _, l := range tableLeaves() {
		if handlers[l.Key] == nil {
			continue
		}
		c := commandWithID(moved, strings.Join(l.Key.Path(), "."))
		for _, id := range l.Today {
			if old := commandWithID(today, id); old != nil && c != nil {
				var diff []string
				asAtStart(id, func() { diff = tablesFollow(old, c) })
				for _, d := range diff {
					t.Error(d)
				}
			}
		}
	}
	// Each provider of a moved type gets what its old IDs had, read from
	// the tables as the source writes them, with no Carries to give it the
	// same entries a second way; the move runs again on those tables.
	types := slices.Clone(movedTypes)
	tablesAtStart(func() {
		for _, typ := range types {
			var leaves []capability.Leaf
			for _, l := range capability.All() {
				if l.Type == typ {
					l.Carries = nil
				}
				leaves = append(leaves, l)
			}
			moveLeaves(typ, leaves)
		}
		for _, l := range capability.All() {
			if l.State != capability.Built || !slices.Contains(types, l.Type) {
				continue
			}
			id := strings.Join(l.Key.Path(), ".")
			for _, old := range l.Today {
				for _, tb := range idTables() {
					v, ok := idTablesAtStart[tb.name][old]
					if got, has := tb.get(id); ok && (!has || !sameEntry(got, v) && !noCheck(v)) {
						t.Errorf("%s: %s says %q for %s, %q for %s", tb.name, tb.name, entryText(v, ok), old, entryText(got, has), id)
					}
				}
			}
		}
	})
	// the check bites: a leaf whose ID no table knows yet differs from
	// cache redis raw, which hides personal data
	var in leafInput
	root := probeRoot(t, &in)
	probe, _, _ := root.Find([]string{"cache", "probeprov", "probe"})
	keys, _, _ := root.Find([]string{"cache", "redis", "raw"})
	if d := tablesFollow(keys, probe); !slices.ContainsFunc(d, func(s string) bool { return strings.HasPrefix(s, "personalCmds") }) {
		t.Errorf("the check missed the masking switch: %v", d)
	}
}

// The tables keyed by command ID as the source writes them: Go sets every
// package variable before the first init function runs, so no type has
// moved yet.
var (
	idTablesAtStart = func() map[string]map[string]any {
		at := map[string]map[string]any{}
		for _, tb := range idTables() {
			at[tb.name] = map[string]any{}
			for _, id := range tb.ids() {
				at[tb.name][id], _ = tb.get(id)
			}
		}
		return at
	}()
	cmdKeysAtStart       = maps.Clone(cmdKeys)
	providerIDsAtStart   = maps.Clone(providerIDs)
	providerOrderAtStart = maps.Clone(providerOrder)
)

// asAtStart runs f with id's entries in cmdKeys and idTables as the source
// wrote them, before its type moved, so today's command answers as it did.
func asAtStart(id string, f func()) {
	var undo []func()
	for _, tb := range idTables() {
		v, ok := idTablesAtStart[tb.name][id]
		if !ok {
			continue
		}
		if was, had := tb.get(id); had {
			undo = append(undo, func() { tb.set(id, was) })
		} else {
			undo = append(undo, func() { tb.drop(id) })
		}
		tb.set(id, v)
	}
	if k, ok := cmdKeysAtStart[id]; ok {
		was, had := cmdKeys[id]
		cmdKeys[id] = k
		undo = append(undo, func() {
			if had {
				cmdKeys[id] = was
			} else {
				delete(cmdKeys, id)
			}
		})
	}
	defer func() {
		for _, u := range undo {
			u()
		}
	}()
	f()
}

// tablesAtStart runs f with every table moveType changes as the source
// wrote it and no type moved, then puts them back as they were.
func tablesAtStart(f func()) {
	type saved struct {
		tb  idTable
		now map[string]any
	}
	var all []saved
	for _, tb := range idTables() {
		now := map[string]any{}
		for _, id := range tb.ids() {
			now[id], _ = tb.get(id)
		}
		all = append(all, saved{tb, now})
	}
	put := func(tb idTable, m map[string]any) {
		for _, id := range tb.ids() {
			tb.drop(id)
		}
		for id, v := range m {
			tb.set(id, v)
		}
	}
	keys, ids, order, moved := cmdKeys, providerIDs, providerOrder, movedTypes
	defer func() {
		cmdKeys, providerIDs, providerOrder, movedTypes = keys, ids, order, moved
		for _, a := range all {
			put(a.tb, a.now)
		}
	}()
	cmdKeys, providerIDs, providerOrder = maps.Clone(cmdKeysAtStart), maps.Clone(providerIDsAtStart), maps.Clone(providerOrderAtStart)
	movedTypes = nil
	for _, a := range all {
		put(a.tb, idTablesAtStart[a.tb.name])
	}
	f()
}

// carriesEntry is whether got, what a leaf has in a table, holds the entry v
// of a command it carries as joinEntry joins them: v itself, a table that
// asks nothing, the first of two reasons, or a list with all of v's flags.
func carriesEntry(got, v any) bool {
	switch {
	case sameEntry(got, v), noCheck(v), isString(got) && isString(v):
		return true
	case isStrings(got) && isStrings(v):
		return !slices.ContainsFunc(v.([]string), func(f string) bool { return !slices.Contains(got.([]string), f) })
	}
	return false
}

// When a type moves, each of its built leaves carries every entry that the
// IDs it names (Today and Carries) had in the tables keyed by command ID,
// whichever provider it is; the providers of one key carry the same
// entries; and no table keeps an ID that only a moved type named.
func TestMovedLeavesCarryTheirTables(t *testing.T) {
	stays := map[string]bool{} // IDs a command still has
	for _, l := range capability.All() {
		if l.State != capability.Built {
			continue
		}
		if handlers[l.Key] != nil {
			stays[strings.Join(l.Key.Path(), ".")] = true
		} else {
			for _, id := range slices.Concat(l.Today, l.Carries) {
				stays[id] = true
			}
		}
	}
	inTree := map[string]bool{}
	walk(newRoot(tcl), func(c *cobra.Command) { inTree[cmdID(c)] = true })
	gone := map[string]bool{}
	byKey := map[string]map[string]string{} // a key's entries, by the leaf that has them
	for _, l := range capability.All() {
		if l.State != capability.Built || !slices.Contains(movedTypes, l.Type) && !(l.Type == "" && slices.Contains(movedTop, l.Verb)) {
			continue
		}
		id := strings.Join(l.Key.Path(), ".")
		var has []string
		for _, tb := range idTables() {
			for _, old := range slices.Concat(l.Today, l.Carries) {
				v, ok := idTablesAtStart[tb.name][old]
				if !ok {
					continue
				}
				if _, needs := gateNetwork[id]; needs && tb.name == "gateNoNetwork" {
					continue // a leaf that needs a network (host ssh exec) is in no gateNoNetwork
				}
				if got, ok := tb.get(id); !ok || !carriesEntry(got, v) {
					t.Errorf("%s: %s does not carry the entry of %s", tb.name, id, old)
				}
			}
			has = append(has, tb.name+"="+entryText(tb.get(id)))
		}
		key := fmt.Sprint(safetyKey{l.Type, l.Area, l.Verb}, " carrying ", l.Carries)
		if byKey[key] == nil {
			byKey[key] = map[string]string{}
		}
		byKey[key][id] = strings.Join(has, " ")
		olds := l.Today
		if l.Type == "" {
			olds = slices.Concat(l.Today, l.Carries) // a moved top-level leaf retires what it carries
		}
		for _, old := range olds {
			if !stays[old] {
				gone[old] = true
			}
		}
		for _, old := range l.Carries { // a carried command left once the tree no longer has it
			if !stays[old] && !inTree[old] {
				gone[old] = true
			}
		}
	}
	for _, g := range capability.Groups() { // a group whose commands all left
		if !inTree[g] && slices.ContainsFunc(slices.Collect(maps.Keys(gone)), func(id string) bool { return strings.HasPrefix(id, g+".") }) {
			gone[g] = true
		}
	}
	for key, leaves := range byKey {
		if vals := slices.Compact(slices.Sorted(maps.Values(leaves))); len(vals) > 1 {
			t.Errorf("the leaves of %s carry different entries: %v", key, leaves)
		}
	}
	for _, tb := range idTables() {
		for _, id := range slices.Sorted(maps.Keys(idTablesAtStart[tb.name])) {
			if _, ok := tb.get(id); !ok && !gone[id] {
				t.Errorf("%s lost %s, which a command still has", tb.name, id)
			}
		}
	}
	for _, old := range slices.Sorted(maps.Keys(gone)) {
		if inTree[old] {
			continue // a noun (audit) keeps the ID of the command that moved under it
		}
		if _, ok := cmdKeys[old]; ok {
			t.Errorf("cmdKeys still has %s, which no command has", old)
		}
		for _, tb := range idTables() {
			if _, ok := tb.get(old); ok {
				t.Errorf("%s still has %s, which no command has", tb.name, old)
			}
		}
	}
}

